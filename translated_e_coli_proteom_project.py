compressed_path = "UP000000625_83333.fasta.gz"


if not os.path.exists(compressed_path):
    print("Downloading E. coli proteome from UniProt...")
    urllib.request.urlretrieve(url, compressed_path)
    print("Download complete.")

proteins = []
current_header = None
seq_parts = []

with gzip.open(compressed_path, "rt", encoding="utf-8") as f:
    for line in f:
        line = line.strip()
        if not line:
            continue

        if line.startswith(">"):
            if current_header is not None:
                proteins.append((current_header, "".join(seq_parts)))
            current_header = line[1:]
            seq_parts = []
        else:
            seq_parts.append(line)

if current_header is not None:
    proteins.append((current_header, "".join(seq_parts)))

